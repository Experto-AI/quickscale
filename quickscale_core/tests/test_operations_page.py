"""The managed operations page renderer and its single user-owned link (SA286).

The generated project's ``quickscale-operations.md`` renders from each
module's declared ``operations`` text and is regenerated by ``quickscale
apply``/``update``/``remove`` under the managed-file hash guard, so these
tests pin the resolution rules both paths share.  The user-owned
``OPERATIONS.md`` names no module value and links the page once; the template
checks live here beside the renderer they exercise.
"""

from __future__ import annotations

from pathlib import Path

from jinja2 import Environment, FileSystemLoader, StrictUndefined
import pytest

import quickscale_core
from quickscale_core.contracts.module_options import STRIPE_API_VERSION
from quickscale_core.generator.operations_page import (
    OPERATIONS_PAGE_RELATIVE_PATH,
    operations_sections,
    render_operations_page,
)
from quickscale_core.generator.runtime_database import runtime_db_template_context

_TEMPLATES_DIR = Path(quickscale_core.__file__).parent / "generator" / "templates"


def _template_env() -> Environment:
    """Mirror the generator's strict Jinja contract for template checks."""
    return Environment(
        loader=FileSystemLoader(str(_TEMPLATES_DIR)),
        keep_trailing_newline=True,
        undefined=StrictUndefined,
    )


def test_path_is_the_managed_root_page() -> None:
    assert OPERATIONS_PAGE_RELATIVE_PATH == "quickscale-operations.md"


def test_the_whole_shipped_set_renders_the_declared_sections() -> None:
    """``None`` means the whole shipped set, matching default generation."""
    sections = operations_sections(None)

    assert [section.module_name for section in sections] == ["billing"]
    section = sections[0]
    assert section.title == "Stripe Billing"
    # Every referenced token is resolved: the declared values, the core
    # contract token, and the configured option's name.
    assert section.values == {
        "webhook_endpoint": "/billing/webhooks/stripe/",
        "webhook_events": (
            "invoice.paid",
            "invoice.payment_failed",
            "checkout.session.completed",
            "checkout.session.expired",
            "checkout.session.async_payment_succeeded",
            "checkout.session.async_payment_failed",
            "customer.subscription.*",
        ),
        "webhook_secret_env_var": "QUICKSCALE_BILLING_WEBHOOK_SECRET",
        "stripe_api_version": STRIPE_API_VERSION,
    }
    assert "https://<your-host>/billing/webhooks/stripe/" in section.text
    assert (
        "invoice.paid, invoice.payment_failed, checkout.session.completed, "
        "checkout.session.expired, checkout.session.async_payment_succeeded, "
        "checkout.session.async_payment_failed, customer.subscription.*."
    ) in section.text
    assert STRIPE_API_VERSION in section.text
    assert "QUICKSCALE_BILLING_WEBHOOK_SECRET" in section.text
    assert "{webhook_events}" not in section.text
    assert "{stripe_api_version}" not in section.text
    assert "{webhook_secret_env_var}" not in section.text


def test_selection_limits_the_sections() -> None:
    assert operations_sections(["blog", "forms", "social"]) == []
    assert operations_sections([]) == []


def test_configured_option_name_moves_the_variable_in_the_text() -> None:
    """A renamed ``*_env_var`` option renames the rendered variable (SA286)."""
    sections = operations_sections(
        ["billing"],
        {"billing": {"webhook_secret_env_var": "ACME_STRIPE_SECRET"}},
    )

    (section,) = sections
    assert section.values["webhook_secret_env_var"] == "ACME_STRIPE_SECRET"
    assert "ACME_STRIPE_SECRET" in section.text
    assert "QUICKSCALE_BILLING_WEBHOOK_SECRET" not in section.text


def test_blank_option_name_contributes_no_value() -> None:
    """A blank variable name renders empty and records no module value."""
    sections = operations_sections(
        ["billing"], {"billing": {"webhook_secret_env_var": ""}}
    )

    (section,) = sections
    assert "webhook_secret_env_var" not in section.values
    assert "QUICKSCALE_BILLING_WEBHOOK_SECRET" not in section.text
    assert "{webhook_secret_env_var}" not in section.text


def test_false_and_zero_options_render_and_are_recorded(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A valid ``False`` or ``0`` option renders as itself, never as blank.

    Only a genuinely absent value contributes nothing; a truthiness test
    would silently erase both, and the section would lose a module value the
    closed-world guard must know about (round 1 finding F-001).
    """
    import quickscale_core.contracts.resolvers as resolvers
    import quickscale_core.generator.operations_page as operations_page_module
    from quickscale_core.manifest.schema import (
        ConfigOption,
        ModuleManifest,
        ModuleOperations,
    )

    manifest = ModuleManifest(
        name="fake",
        version="1.0.0",
        mutable_options={
            "enabled": ConfigOption(
                name="enabled",
                option_type="boolean",
                default=True,
                django_setting="FAKE_ENABLED",
                description="Enabled switch",
                validation={},
            ),
            "retries": ConfigOption(
                name="retries",
                option_type="integer",
                default=3,
                django_setting="FAKE_RETRIES",
                description="Retry count",
                validation={},
            ),
        },
        operations=ModuleOperations(
            title="Fake",
            text="Enabled: {enabled}; retries: {retries}",
            values={},
        ),
    )
    monkeypatch.setattr(
        operations_page_module,
        "load_module_manifest_with_fallback",
        lambda module_name: manifest,
    )
    monkeypatch.setattr(
        resolvers, "load_module_manifest_with_fallback", lambda module_name: manifest
    )

    (section,) = operations_page_module.operations_sections(
        ["fake"], {"fake": {"enabled": False, "retries": 0}}
    )

    assert "Enabled: False; retries: 0" in section.text
    assert section.values["enabled"] == "False"
    assert section.values["retries"] == "0"


def test_render_orders_sections_and_terminates_the_file() -> None:
    page = render_operations_page(None)

    assert page.startswith("# Module operations\n")
    assert "\n## Stripe Billing\n" in page
    assert page.endswith("stay consistent.\n")


def test_render_empty_selection_is_the_header_only() -> None:
    """The header renders without a module, so the guide's link resolves."""
    page = render_operations_page([])

    assert page == render_operations_page(["blog"])
    assert page.startswith("# Module operations\n")
    assert "## " not in page


def test_generation_template_renders_exactly_its_context_value() -> None:
    """The emission template adds no whitespace around the rendered page."""
    rendered = (
        _template_env()
        .get_template("quickscale-operations.md.j2")
        .render(operations_page="# Module operations\n")
    )

    assert rendered == "# Module operations\n"


def test_operations_guide_links_the_managed_page_once_and_names_no_module_value() -> (
    None
):
    """The user-owned guide carries one link and none of the moved values."""
    env = _template_env()
    template = env.get_template("OPERATIONS.md.j2")
    context = {
        "project_name": "testproject",
        "package_name": "testproject",
        "selected_modules": None,
        **runtime_db_template_context("testproject"),
    }

    rendered = template.render(context)

    assert rendered.count(OPERATIONS_PAGE_RELATIVE_PATH) == 1
    assert rendered.count("](") == 1, (
        "the guide carries exactly one link to the managed page"
    )
    for moved in (
        "Stripe",
        "invoice.paid",
        "QUICKSCALE_BILLING_WEBHOOK_SECRET",
        STRIPE_API_VERSION,
        "billing",
    ):
        assert moved not in rendered, (
            f"the user-owned guide must not name the module value {moved!r}; "
            "it belongs to the managed quickscale-operations.md page"
        )
    # The guide no longer varies with the module selection, so a project
    # without billing still links the managed page.
    assert rendered == template.render({**context, "selected_modules": ["billing"]})
