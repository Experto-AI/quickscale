"""The managed CI environment renderer (SA286).

The generated project's ``.github/quickscale-ci-env`` renders from each
module's declared ``ci_env`` placeholders and is regenerated by
``quickscale apply``/``update``/``remove`` under the managed-file hash guard,
so these tests pin the resolution rules both paths share.
"""

from __future__ import annotations

import pytest

from quickscale_core.generator.ci_environment import (
    CI_ENVIRONMENT_RELATIVE_PATH,
    ci_environment_entries,
    render_ci_environment,
)


def test_path_is_the_managed_github_file() -> None:
    assert CI_ENVIRONMENT_RELATIVE_PATH == ".github/quickscale-ci-env"


def test_the_whole_shipped_set_renders_every_declared_placeholder() -> None:
    """``None`` means the whole shipped set, matching default generation."""
    assert ci_environment_entries(None) == {
        "POSTHOG_API_KEY": "ph_test_ci",
        "QUICKSCALE_BILLING_WEBHOOK_SECRET": "whsec_test_ci",
        "QUICKSCALE_NOTIFICATIONS_WEBHOOK_SECRET": "whsec_YWFhYWFhYWFhYWFhYWFhYQ==",
        "RESEND_API_KEY": "re_test_ci",
        "STRIPE_PUBLISHABLE_KEY": "pk_test_ci",
        "STRIPE_SECRET_KEY": "sk_test_ci",
    }


def test_selection_limits_the_entries() -> None:
    assert ci_environment_entries(["notifications"]) == {
        "RESEND_API_KEY": "re_test_ci",
        "QUICKSCALE_NOTIFICATIONS_WEBHOOK_SECRET": "whsec_YWFhYWFhYWFhYWFhYWFhYQ==",
    }
    assert ci_environment_entries(["blog", "forms", "social"]) == {}
    assert ci_environment_entries([]) == {}


def test_configured_option_name_moves_the_variable() -> None:
    """A renamed ``*_env_var`` option renames the CI variable (SA286)."""
    assert ci_environment_entries(
        ["billing"],
        {"billing": {"webhook_secret_env_var": "ACME_STRIPE_SECRET"}},
    ) == {
        "STRIPE_PUBLISHABLE_KEY": "pk_test_ci",
        "STRIPE_SECRET_KEY": "sk_test_ci",
        "ACME_STRIPE_SECRET": "whsec_test_ci",
    }


def test_blank_option_name_contributes_nothing() -> None:
    """A blank variable name means the module reads no credential under it."""
    assert ci_environment_entries(
        ["notifications"], {"notifications": {"resend_api_key_env_var": ""}}
    ) == {
        "QUICKSCALE_NOTIFICATIONS_WEBHOOK_SECRET": "whsec_YWFhYWFhYWFhYWFhYWFhYQ==",
    }


def test_conflicting_placeholders_fail_hard() -> None:
    """One variable name may not carry two different placeholders."""
    with pytest.raises(ValueError, match="ONE_OWNER_KEY"):
        ci_environment_entries(
            ["billing", "notifications"],
            {
                "billing": {"secret_key_env_var": "ONE_OWNER_KEY"},
                "notifications": {"resend_api_key_env_var": "ONE_OWNER_KEY"},
            },
        )


def test_unusable_resolved_name_fails_hard() -> None:
    """A resolved name that cannot form a NAME=value line is refused."""
    with pytest.raises(ValueError, match="not usable in a NAME=value"):
        ci_environment_entries(["billing"], {"billing": {"secret_key_env_var": "A=B"}})


def test_render_sorts_and_terminates_every_line() -> None:
    rendered = render_ci_environment({"ZED_KEY": "z", "ALPHA_KEY": "a", "MID_KEY": "m"})
    assert rendered == "ALPHA_KEY=a\nMID_KEY=m\nZED_KEY=z\n"


def test_render_empty_is_empty() -> None:
    """No declared entry renders an empty file the load step appends safely."""
    assert render_ci_environment({}) == ""
