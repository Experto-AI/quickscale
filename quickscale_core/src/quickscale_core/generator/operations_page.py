"""The generated project's managed operations page (SA286).

The generated ``OPERATIONS.md`` is user-owned, so it names no module value:
the operator-facing details an installed module owns — vendor versions,
webhook events, endpoints — live in the managed ``quickscale-operations.md``
page instead, and the guide links that page once (Markdown has no include
directive).  Each module authors its section in its own ``module.yml``
``operations`` section; the text's ``{name}`` tokens resolve at render time
from the module's declared values, the module's configured options, and the
core contract tokens, so a project that renames a ``*_env_var`` option keeps
its page accurate without editing a user-owned file, and a module release
that changes a version, an event list, or an endpoint reaches the project
through ``apply``/``update`` alone.

Generation writes the page from the shipped manifests; ``quickscale apply``,
``quickscale update``, and ``quickscale remove`` regenerate it under the
managed-file hash guard beside the managed seam files and the managed CI
environment file (the path is part of
``quickscale_core.project_state_hashes.DEFAULT_MANAGED_PROJECT_PATHS``).
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from typing import Any

from quickscale_core.contracts.module_catalog import MODULE_CATALOG
from quickscale_core.contracts.module_options import ADOPTION_STEP_TOKENS
from quickscale_core.contracts.resolvers import (
    load_module_manifest_with_fallback,
    resolve_manifest_module_options,
)

__all__ = [
    "OPERATIONS_PAGE_RELATIVE_PATH",
    "OperationsSection",
    "operations_sections",
    "render_operations_page",
]

#: Project-relative path of the managed operations page.  Generation emits
#: it from :func:`render_operations_page`, and ``apply``/``update``/
#: ``remove`` regenerate it under the managed-file hash guard, so a local
#: edit is reported as drift.
OPERATIONS_PAGE_RELATIVE_PATH = "quickscale-operations.md"

#: The fixed page header.  It carries no module value and no project name,
#: so generation and regeneration agree on one content for one module set.
_PAGE_HEADER = (
    "# Module operations\n"
    "\n"
    "> Managed by QuickScale. Regenerated by `quickscale apply` and `quickscale update` from\n"
    "> the installed modules' own declarations; the generated project's `OPERATIONS.md` names\n"
    "> no module value and links here once. A local edit is reported as drift.\n"
)


@dataclass(frozen=True)
class OperationsSection:
    """One module's rendered operations section.

    Attributes:
        module_name: The module that owns the section.
        title: The section heading, from the module's declaration.
        text: The rendered Markdown body, with every referenced token
            resolved.
        values: The module-owned values the section carries, keyed by token
            name: the module's declared ``values`` entries plus the resolved
            values of the ``{name}`` tokens the text references.  A declared
            group stays a tuple, whose entries are individually-guarded
            values.
    """

    module_name: str
    title: str
    text: str
    values: dict[str, str | tuple[str, ...]] = field(default_factory=dict)


def _module_names(module_names: Iterable[str] | None) -> list[str]:
    """Return the selected module names, deduplicated and sorted.

    Sorting keeps generation and ``apply``/``update`` on one section order,
    so one module set always renders one page content.
    """
    if module_names is None:
        names = [entry.name for entry in MODULE_CATALOG]
    else:
        names = list(module_names)
    return sorted(dict.fromkeys(names))


def _render_value(value: str | tuple[str, ...]) -> str:
    """Return the text one declared value renders as.

    A declared group renders as its entries joined by a comma, while each
    entry stays an individually-guarded value.
    """
    if isinstance(value, tuple):
        return ", ".join(value)
    return value


def _option_text(value: Any) -> str:
    """Return the text one resolved option contributes to the page.

    A genuinely absent value contributes nothing; every other value renders
    as its string form, so a valid ``False`` or ``0`` option is never
    silently erased the way a truthiness test would erase it.
    """
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    return str(value)


def _resolve_text(
    text: str,
    declared_values: Mapping[str, str | tuple[str, ...]],
    option_values: Mapping[str, str],
) -> tuple[str, dict[str, str | tuple[str, ...]]]:
    """Resolve the ``{name}`` tokens in one operations text.

    Precedence is the module's declared value, then its resolved option,
    then a core contract token; the loader already refuses a declared value
    that would shadow either other namespace.  Only tokens present in the
    text are substituted — the ``resolve_adoption_step_tokens`` contract:
    prose that embeds unrelated braces is never rewritten.  The returned
    mapping carries every declared value (a declared group kept as its
    tuple) plus each referenced option or core token's resolved value, so a
    blank option contributes no value a user-owned file must avoid naming.

    Returns:
        The rendered text and the module-owned values it carries.
    """
    values: dict[str, str | tuple[str, ...]] = dict(declared_values)
    rendered = text
    for name, value in declared_values.items():
        rendered = rendered.replace("{" + name + "}", _render_value(value))
    for name, value in option_values.items():
        marker = "{" + name + "}"
        if marker not in rendered:
            continue
        rendered = rendered.replace(marker, value)
        if value:
            values.setdefault(name, value)
    for name, value in ADOPTION_STEP_TOKENS.items():
        marker = "{" + name + "}"
        if marker in rendered:
            rendered = rendered.replace(marker, value)
            values.setdefault(name, value)
    return rendered, values


def operations_sections(
    module_names: Iterable[str] | None,
    options: Mapping[str, Mapping[str, Any]] | None = None,
) -> list[OperationsSection]:
    """Return the resolved operations sections for *module_names*.

    Each selected module's ``operations`` declaration resolves through the
    manifest engine with that module's supplied options (or its declared
    defaults), so a token that references a ``*_env_var`` option renders the
    project's configured name.  A module without an ``operations``
    declaration contributes no section.

    Args:
        module_names: The module selection; ``None`` means the whole shipped
            module set, and an empty iterable means no module.
        options: Configured module options keyed by module name; a module
            absent from the mapping resolves against its declared defaults.

    Returns:
        The sections, sorted by module name.
    """
    resolved_options = options or {}
    sections: list[OperationsSection] = []
    for module_name in _module_names(module_names):
        manifest = load_module_manifest_with_fallback(module_name)
        if manifest.operations is None:
            continue
        resolved = resolve_manifest_module_options(
            module_name, resolved_options.get(module_name)
        )
        option_values = {
            option_name: _option_text(resolved.get(option_name))
            for option_name in manifest.get_all_options()
        }
        text, values = _resolve_text(
            manifest.operations.text,
            manifest.operations.values,
            option_values,
        )
        sections.append(
            OperationsSection(
                module_name=module_name,
                title=manifest.operations.title,
                text=text,
                values=values,
            )
        )
    return sections


def render_operations_page(
    module_names: Iterable[str] | None,
    options: Mapping[str, Mapping[str, Any]] | None = None,
) -> str:
    """Render the managed operations page for *module_names*.

    The page carries one ``## <title>`` section per module that declares an
    ``operations`` section, in module-name order, so generation and
    ``apply``/``update`` agree on one content for one module set.  The
    header renders even when no module declares one, so the user-owned
    ``OPERATIONS.md`` link always resolves.
    """
    parts = [_PAGE_HEADER]
    for section in operations_sections(module_names, options):
        parts.append(f"\n## {section.title}\n\n{section.text.rstrip()}\n")
    return "".join(parts)
