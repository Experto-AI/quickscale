INCIDENTAL_NAMES = frozenset(
    {"P", "R", "T", "Any", "TypeVar", "ParamSpec", "annotations", "re", "json", "cast"}
)


@pytest.mark.parametrize("module_path", sorted(SURFACES))
def test_public_surface_importable(module_path: str) -> None:
    """Every pinned public name is present on the facade."""
    surface = SURFACES[module_path]
    module = importlib.import_module(module_path)
    missing = sorted(set(surface["expected"]) - set(dir(module)))
    assert not missing, f"{module_path} is missing public names: {missing}"


@pytest.mark.parametrize("module_path", sorted(SURFACES))
def test_surface_pins_no_private_or_incidental_names(module_path: str) -> None:
    """The expected sets name public facade API only."""
    expected = set(SURFACES[module_path]["expected"])
    for name in expected:
        assert not name.startswith("_"), f"{module_path} pins private {name!r}"
    incidental = expected & INCIDENTAL_NAMES
    assert not incidental, f"{module_path} pins incidental names: {sorted(incidental)}"


@pytest.mark.parametrize("module_path", sorted(SURFACES))
def test_reexports_are_the_defining_objects(module_path: str) -> None:
    """A re-export is the same object as its defining module's binding."""
    surface = SURFACES[module_path]
    module = importlib.import_module(module_path)
    for name, source in surface["identity"].items():
        defining = importlib.import_module(source)
        value = getattr(defining, name)
        if isinstance(value, (dict, list, set)):
            # Mutable registries are rebuildable test fixtures, not identity seams.
            continue
        assert getattr(module, name) is value, (
            f"{module_path}.{name} is not {source}.{name}"
        )


@pytest.mark.parametrize("module_path", sorted(SURFACES))
def test_core_version_alias_matches_core(module_path: str) -> None:
    """The ``quickscale_version`` alias mirrors ``quickscale_core.__version__``."""
    import quickscale_core

    module = importlib.import_module(module_path)
    if "quickscale_version" in dir(module):
        assert module.quickscale_version == quickscale_core.__version__
