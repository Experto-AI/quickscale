def test_facade_preserves_former_module_surface() -> None:
    """Every name the former module exposed stays importable from the package."""
    missing = sorted(EXPECTED_MODULE_SURFACE - set(dir(beta_migration)))
    assert not missing, f"facade dropped former module names: {missing}"


def test_facade_reexports_report_rendering_helpers() -> None:
    """The report helpers stay importable from the original module path."""
    assert beta_migration.render_report_json is report_rendering.render_report_json
    assert (
        beta_migration.render_report_summary is report_rendering.render_report_summary
    )
    assert beta_migration.write_report_file is report_rendering.write_report_file


def test_facade_reexports_handoff_prompt_surface() -> None:
    """The handoff prompt constants and writer stay importable."""
    assert (
        beta_migration.HANDOFF_PROMPT_FILENAME == handoff_prompt.HANDOFF_PROMPT_FILENAME
    )
    assert beta_migration.write_handoff_prompt is handoff_prompt.write_handoff_prompt
