"""
Behavioral controls for the SA204(c, h) module migration freeze gate.

The gate is exercised hermetically against a twelve-module fixture tree
installed through the module-discovery override seam, with the manifest
generated by its owning sibling, and the latest release tag read from a
throwaway tagged repository installed through the gate's Git root, so no test
reads or writes the real checked-in manifest or the real repository's tags.

Test matrix
-----------
* ``TestAccepted`` — a current identity is green; a new numbered migration is
  a legal forward addition, recorded or not.
* ``TestRejected`` — an in-place edit, a deletion, a private-symbol reference,
  and a manifest/inventory mismatch each exit 1.
* ``TestAppendOnly`` — a released value that changed or disappeared since the
  latest release tag fails even after ``--write`` re-froze the manifest, an
  addition stays legal, the highest release version is the one compared, and
  an absent or manifest-predating tag passes with a notice.
* ``TestFailClosed`` — malformed manifests, uninspectable module trees, and
  discovery failures exit 2.
* ``TestRepositoryTree`` — the real checked-in tree is green.
"""

