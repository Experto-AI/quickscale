"""
Behavioral controls for the SA204(c) module migration freeze gate.

The gate is exercised hermetically against a twelve-module fixture tree
installed through the module-discovery override seam, with the manifest
generated by its owning sibling, so no test reads or writes the real
checked-in manifest under ``scripts/``.

Test matrix
-----------
* ``TestAccepted`` — a current identity is green; a new numbered migration is
  a legal forward addition, recorded or not.
* ``TestRejected`` — an in-place edit, a deletion, a private-symbol reference,
  and a manifest/inventory mismatch each exit 1.
* ``TestFailClosed`` — malformed manifests, uninspectable module trees, and
  discovery failures exit 2.
"""

from __future__ import annotations

import json
import shutil
from collections.abc import Callable, Iterator
from pathlib import Path

import pytest

import scripts.check_migration_freeze as check_migration_freeze
import scripts.sync_migration_hashes as sync_migration_hashes
from quickscale_core.contracts import module_discovery

MODEL_MODULES: tuple[str, ...] = (
    "auth",
    "backups",
    "billing",
    "blog",
    "crm",
    "forms",
    "listings",
    "notifications",
    "orgs",
    "social",
)
SERVICE_MODULES: tuple[str, ...] = ("analytics", "storage")


def _build_modules_fixture(root: Path) -> None:
    """Create the twelve shipped modules with migration files where they ship them."""
    for name in MODEL_MODULES:
        module_dir = root / name
        package_dir = module_dir / "src" / f"quickscale_modules_{name}"
        migrations_dir = package_dir / "migrations"
        migrations_dir.mkdir(parents=True)
        (module_dir / "module.yml").write_text(f"name: {name}\n")
        (package_dir / "__init__.py").write_text("")
        (migrations_dir / "__init__.py").write_text("")
        (migrations_dir / "0001_initial.py").write_text(f"# {name} initial migration\n")
    for name in SERVICE_MODULES:
        module_dir = root / name
        package_dir = module_dir / "src" / f"quickscale_modules_{name}"
        package_dir.mkdir(parents=True)
        (module_dir / "module.yml").write_text(f"name: {name}\n")
        (package_dir / "__init__.py").write_text("")


@pytest.fixture
def manifest_path(tmp_path: Path) -> Path:
    """Return a manifest path outside the repository tree."""
    return tmp_path / "migration_hashes.json"


@pytest.fixture
def modules_fixture(tmp_path: Path) -> Iterator[Path]:
    """Install a complete twelve-module fixture as the discovery root."""
    modules_root = tmp_path / "quickscale_modules"
    modules_root.mkdir()
    _build_modules_fixture(modules_root)
    original = module_discovery.get_modules_base_path()
    module_discovery.set_modules_base_path(modules_root)
    try:
        yield modules_root
    finally:
        module_discovery.set_modules_base_path(original)


@pytest.fixture
def frozen_manifest(modules_fixture: Path, manifest_path: Path) -> Path:
    """Record the fixture tree with the gate's owning manifest generator."""
    assert sync_migration_hashes.main(["--write", "--manifest", str(manifest_path)]) == 0
    return manifest_path


def _freeze(manifest_path: Path, capsys: pytest.CaptureFixture[str]) -> tuple[int, str, str]:
    """Run the gate and return ``(exit_code, stdout, stderr)``."""
    code = check_migration_freeze.main(["--manifest", str(manifest_path)])
    captured = capsys.readouterr()
    return code, captured.out, captured.err


def _migrations_dir(modules_root: Path, module_name: str) -> Path:
    """Return the fixture module's migrations package."""
    return modules_root / module_name / "src" / f"quickscale_modules_{module_name}" / "migrations"


def _rewrite_manifest_modules(
    manifest_path: Path, mutate: Callable[[dict[str, dict[str, str]]], object]
) -> None:
    """Apply ``mutate`` to the manifest's ``modules`` mapping and write it back."""
    payload = json.loads(manifest_path.read_text(encoding="utf-8"))
    mutate(payload["modules"])
    manifest_path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")


class TestAccepted:
    """The frozen identity is green, and new migrations are forward additions."""

    def test_current_identity_is_green(
        self,
        modules_fixture: Path,
        frozen_manifest: Path,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        code, stdout, stderr = _freeze(frozen_manifest, capsys)

        assert code == 0
        assert "byte-identical" in stdout
        assert stderr == ""

    def test_new_numbered_migration_is_forward_addition(
        self,
        modules_fixture: Path,
        frozen_manifest: Path,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        migrations_dir = _migrations_dir(modules_fixture, "auth")
        (migrations_dir / "0002_add_field.py").write_text("from django.db import migrations\n")

        code, _stdout, stderr = _freeze(frozen_manifest, capsys)

        assert code == 0
        assert stderr == ""

    def test_repository_tree_is_green(self, capsys: pytest.CaptureFixture[str]) -> None:
        """The checked-in manifest matches the real shipped modules."""
        code = check_migration_freeze.main([])
        captured = capsys.readouterr()

        assert code == 0, captured.err


class TestRejected:
    """Every freeze violation exits 1 with a deterministic diagnostic."""

    def test_in_place_edit_rejected(
        self,
        modules_fixture: Path,
        frozen_manifest: Path,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        _migrations_dir(modules_fixture, "auth").joinpath("0001_initial.py").write_text(
            "# auth initial migration, edited\n"
        )

        code, stdout, stderr = _freeze(frozen_manifest, capsys)

        assert code == 1
        assert "auth/0001_initial.py" in stdout
        assert "frozen content changed" in stdout
        assert stderr == ""

    def test_deletion_rejected(
        self,
        modules_fixture: Path,
        frozen_manifest: Path,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        _migrations_dir(modules_fixture, "crm").joinpath("0001_initial.py").unlink()

        code, stdout, _stderr = _freeze(frozen_manifest, capsys)

        assert code == 1
        assert "crm/0001_initial.py" in stdout
        assert "frozen file is missing" in stdout

    def test_private_attribute_reference_rejected(
        self,
        modules_fixture: Path,
        frozen_manifest: Path,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        """The historical ``models._BlogMediaAssetImageField`` shape must fail."""
        initial = _migrations_dir(modules_fixture, "blog") / "0001_initial.py"
        initial.write_text(
            initial.read_text(encoding="utf-8")
            + "value = quickscale_modules_blog.models._HiddenField\n"
        )
        assert sync_migration_hashes.main(["--write", "--manifest", str(frozen_manifest)]) == 0
        capsys.readouterr()

        code, stdout, _stderr = _freeze(frozen_manifest, capsys)

        assert code == 1
        assert "blog/0001_initial.py:2" in stdout
        assert "references private symbol" in stdout
        assert "quickscale_modules_blog.models._HiddenField" in stdout

    @pytest.mark.parametrize(
        ("label", "content", "reference"),
        [
            (
                "private imported name",
                "from quickscale_modules_auth.models import _PrivateThing\n",
                "quickscale_modules_auth.models._PrivateThing",
            ),
            (
                "private module path",
                "from quickscale_modules_auth._helpers import thing\n",
                "quickscale_modules_auth._helpers",
            ),
            (
                "private plain import",
                "import quickscale_modules_auth._helpers\n",
                "quickscale_modules_auth._helpers",
            ),
            (
                "private intermediate module path",
                "from quickscale_modules_auth._internal.fields import StableField\n",
                "quickscale_modules_auth._internal.fields",
            ),
            (
                "private intermediate plain import",
                "import quickscale_modules_auth._internal.fields\n",
                "quickscale_modules_auth._internal.fields",
            ),
        ],
    )
    def test_private_import_shapes_rejected(
        self,
        modules_fixture: Path,
        frozen_manifest: Path,
        capsys: pytest.CaptureFixture[str],
        label: str,
        content: str,
        reference: str,
    ) -> None:
        """An unrecorded forward migration is scanned for private references."""
        (_migrations_dir(modules_fixture, "auth") / "0002_private.py").write_text(content)

        code, stdout, _stderr = _freeze(frozen_manifest, capsys)

        assert code == 1, label
        assert "auth/0002_private.py:1" in stdout, label
        assert reference in stdout, label

    def test_unrecorded_shipped_module_rejected(
        self,
        modules_fixture: Path,
        frozen_manifest: Path,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        _rewrite_manifest_modules(frozen_manifest, lambda modules: modules.pop("crm"))

        code, stdout, _stderr = _freeze(frozen_manifest, capsys)

        assert code == 1
        assert "crm: shipped module has no manifest record" in stdout

    def test_phantom_module_record_rejected(
        self,
        modules_fixture: Path,
        frozen_manifest: Path,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        _rewrite_manifest_modules(frozen_manifest, lambda modules: modules.update(phantom={}))

        code, stdout, _stderr = _freeze(frozen_manifest, capsys)

        assert code == 1
        assert "phantom: recorded in the manifest but not a shipped module" in stdout

    def test_module_losing_migrations_package_rejected(
        self,
        modules_fixture: Path,
        frozen_manifest: Path,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        shutil.rmtree(_migrations_dir(modules_fixture, "forms"))

        code, stdout, _stderr = _freeze(frozen_manifest, capsys)

        assert code == 1
        assert "recorded migrations are gone" in stdout

    def test_non_migration_record_rejected(
        self,
        modules_fixture: Path,
        frozen_manifest: Path,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        _rewrite_manifest_modules(
            frozen_manifest,
            lambda modules: modules["auth"].update({"helpers.py": "0" * 64}),
        )

        code, stdout, _stderr = _freeze(frozen_manifest, capsys)

        assert code == 1
        assert "manifest records a file that is not a numbered migration" in stdout


class TestFailClosed:
    """Malformed or uninspectable inputs exit 2 instead of passing unverified."""

    def test_missing_manifest_is_configuration_error(
        self,
        modules_fixture: Path,
        manifest_path: Path,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        code, _stdout, stderr = _freeze(manifest_path, capsys)

        assert code == 2
        assert "ERROR:" in stderr

    @pytest.mark.parametrize(
        ("label", "content"),
        [
            ("truncated JSON", '{"schema_version": 1, "modules": {'),
            (
                "duplicate key",
                '{"schema_version": 1, "schema_version": 1, "modules": {}}',
            ),
            ("wrong schema version", '{"schema_version": 2, "modules": {}}'),
            ("boolean schema version", '{"schema_version": true, "modules": {}}'),
            ("non-finite description", '{"schema_version": 1, "modules": {}, "description": NaN}'),
            ("modules not an object", '{"schema_version": 1, "modules": []}'),
            (
                "non-string digest",
                '{"schema_version": 1, "modules": {"auth": {"0001_initial.py": 1}}}',
            ),
        ],
    )
    def test_malformed_manifest_is_configuration_error(
        self,
        modules_fixture: Path,
        manifest_path: Path,
        capsys: pytest.CaptureFixture[str],
        label: str,
        content: str,
    ) -> None:
        manifest_path.write_text(content, encoding="utf-8")

        code, _stdout, stderr = _freeze(manifest_path, capsys)

        assert code == 2, label
        assert "ERROR:" in stderr

    def test_undecodable_manifest_is_configuration_error(
        self,
        modules_fixture: Path,
        manifest_path: Path,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        manifest_path.write_bytes(b'{"schema_version": 1, "modules": {}}\xff\xfe')

        code, _stdout, stderr = _freeze(manifest_path, capsys)

        assert code == 2
        assert "ERROR:" in stderr

    def test_uninspectable_migration_source_is_configuration_error(
        self,
        modules_fixture: Path,
        frozen_manifest: Path,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        (_migrations_dir(modules_fixture, "listings") / "0001_initial.py").write_text(
            "def broken(:\n"
        )

        code, _stdout, stderr = _freeze(frozen_manifest, capsys)

        assert code == 2
        assert "AST parse failed" in stderr

    def test_missing_source_package_is_configuration_error(
        self,
        modules_fixture: Path,
        frozen_manifest: Path,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        shutil.rmtree(modules_fixture / "crm" / "src")

        code, _stdout, stderr = _freeze(frozen_manifest, capsys)

        assert code == 2
        assert "no source package" in stderr

    def test_discovery_mismatch_is_configuration_error(
        self,
        modules_fixture: Path,
        frozen_manifest: Path,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        shutil.rmtree(modules_fixture / "social")

        code, _stdout, stderr = _freeze(frozen_manifest, capsys)

        assert code == 2
        assert "Authoritative module inventory is incomplete" in stderr
