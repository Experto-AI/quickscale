class GeneratorError(ValueError):
    """A deterministic malformed-input or invariant failure."""


def _validate_unowned_job_rationales() -> None:
    if frozenset(UNOWNED_JOB_RATIONALES) != EXPECTED_UNOWNED_JOB_IDS:
        raise GeneratorError(
            "unowned hosted-job rationale keys do not match the seven-job exemption set"
        )
    if any(
        not isinstance(reason, str) or not reason.strip()
        for reason in UNOWNED_JOB_RATIONALES.values()
    ):
        raise GeneratorError("every unowned hosted job must have a nonempty rationale")


class _DuplicateYamlKeyError(ValueError):
    """Raised by the strict BaseLoader constructor for duplicate keys."""


def _yaml_mapping(loader: Any, node: Any) -> dict[Any, Any]:
    mapping: dict[Any, Any] = {}
    seen: set[Any] = set()
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node, deep=False)
        if key in seen:
            raise _DuplicateYamlKeyError(f"Duplicate YAML key: {key!r}")
        seen.add(key)
        mapping[key] = loader.construct_object(value_node, deep=False)
    return mapping


def _parse_workflow(text: str, label: str) -> dict[str, Any]:
    """Parse YAML with BaseLoader semantics and duplicate-key rejection."""
    if yaml is None:
        raise GeneratorError("PyYAML is not available")
    loader_type: Any = type("StrictBaseLoader", (yaml.BaseLoader,), {})
    loader_type.add_constructor(
        yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG,
        _yaml_mapping,
    )
    try:
        value = yaml.load(text, Loader=loader_type)
    except _DuplicateYamlKeyError as exc:
        raise GeneratorError(f"{label}: {exc}") from None
    except yaml.YAMLError as exc:
        raise GeneratorError(f"{label}: YAML parse error: {exc}") from None
    except Exception as exc:
        raise GeneratorError(f"{label}: YAML parse error: {exc}") from None
    if not isinstance(value, dict):
        raise GeneratorError(f"{label}: workflow must be a YAML mapping")
    return value


def _parse_registry(path: Path) -> list[dict[str, Any]]:
    """Load the registry with the parity checker's authoritative schema."""
    if SchemaValidationError is None or _parse_json_strict is None or _validate_registry is None:
        raise GeneratorError("registry: authoritative parity validator is unavailable")
    try:
        raw = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise GeneratorError(f"cannot read registry {path}: {exc}") from None
    try:
        data = _parse_json_strict(raw, str(path))
        return _validate_registry(data)
    except SchemaValidationError as exc:
        location = f"{exc.source}:{exc.path}" if exc.path else exc.source
        raise GeneratorError(f"{location}: {exc.message}") from None


def _registry_bindings(gates: list[dict[str, Any]]) -> dict[str, tuple[str, str]]:
    """Validate and return the supported hosted gate bindings."""
    hosted = [
        gate
        for gate in gates
        if "hosted" in gate["required_contexts"] or gate["bindings"].get("ci_job") is not None
    ]
    hosted_ids = tuple(gate["id"] for gate in hosted)
    if hosted_ids != HOSTED_GATE_ORDER:
        raise GeneratorError(
            "unsupported hosted gate set: "
            f"expected {list(HOSTED_GATE_ORDER)!r}, got {list(hosted_ids)!r}"
        )
    bindings: dict[str, tuple[str, str]] = {}
    for gate in hosted:
        ci_job = gate["bindings"].get("ci_job")
        make_target = gate["bindings"].get("make_target")
        if not isinstance(ci_job, str) or not isinstance(make_target, str):
            raise GeneratorError(f"hosted gate {gate['id']!r} has incomplete bindings")
        bindings[gate["id"]] = (ci_job, make_target)
    return bindings


def _expected_needs(gates: list[dict[str, Any]]) -> dict[str, tuple[str, ...]]:
    bindings = _registry_bindings(gates)
    needs: dict[str, tuple[str, ...]] = {}
    for consumer, gate_ids in NEEDS_GATE_IDS.items():
        try:
            registry_jobs = tuple(bindings[gate_id][0] for gate_id in gate_ids)
        except KeyError as exc:  # defensive: _registry_bindings checked the set
            raise GeneratorError(
                f"needs policy references unsupported gate {exc.args[0]!r}"
            ) from None
        needs[consumer] = FIXED_NEEDS + registry_jobs
    return needs


def _check_gate_targets(gates: list[dict[str, Any]]) -> str:
    """Return registry-bound ``check-*`` targets for Make's parse-time use."""
    targets = tuple(
        gate["bindings"]["make_target"]
        for gate in gates
        if isinstance(gate.get("bindings"), dict)
        and isinstance(gate["bindings"].get("make_target"), str)
        and gate["bindings"]["make_target"].startswith("check-")
    )
    if not targets:
        raise GeneratorError("registry: no check-* Make targets are declared")
    return " ".join(targets)


def _expected_e2e_paths(gates: list[dict[str, Any]]) -> tuple[str, ...]:
    """Flatten E2E trigger inputs in registry declaration order."""
    paths: list[str] = []
    for gate in gates:
        if "e2e-trigger" in gate["required_contexts"]:
            trigger_inputs = gate["trigger_inputs"]
            if not isinstance(trigger_inputs, list) or not all(
                isinstance(path, str) for path in trigger_inputs
            ):
                raise GeneratorError(f"gate {gate['id']!r} trigger_inputs must be path strings")
            paths.extend(trigger_inputs)
    return tuple(paths)


def _parse_e2e_workflow(text: str) -> dict[str, Any]:
    """Parse E2E YAML and require exactly one pull-request path sequence."""
    workflow = _parse_workflow(text, "e2e.yml")
    trigger = workflow.get("on")
    if not isinstance(trigger, dict):
        raise GeneratorError("e2e.yml: on must be a mapping")
    pull_request = trigger.get("pull_request")
    if not isinstance(pull_request, dict):
        raise GeneratorError("e2e.yml: on.pull_request must be a mapping")
    paths = pull_request.get("paths")
    if not isinstance(paths, list) or not all(isinstance(path, str) for path in paths):
        raise GeneratorError("e2e.yml: on.pull_request.paths must be a sequence of strings")
    return workflow


def _job_steps(job: dict[str, Any], job_id: str) -> list[dict[str, Any]]:
    steps = job.get("steps")
    if not isinstance(steps, list) or not all(isinstance(step, dict) for step in steps):
        raise GeneratorError(f"jobs.{job_id}.steps must be a list of mappings")
    return steps


def _locate_hosted_jobs(
    jobs: dict[str, Any], label: str, *, allow_missing: bool = False
) -> dict[str, str]:
    """
    Locate the sixteen hosted jobs by their static catalog display names.

    Display metadata is helper-owned and static, so the generated job IDs may
    be stale before an edit: a registry ``ci_job`` (F-005) or Make-target
    change must be projectable by ``--write`` without treating the previously
    generated job IDs as drift.
    """
    located: dict[str, str] = {}
    for gate_id in HOSTED_GATE_ORDER:
        spec = HOSTED_JOB_CATALOG[gate_id]
        matches = [
            job_id
            for job_id, job in jobs.items()
            if isinstance(job, dict) and job.get("name") == spec.display_name
        ]
        if not matches and allow_missing:
            continue
        if len(matches) != 1:
            raise GeneratorError(f"{label}: expected exactly one job named {spec.display_name!r}")
        located[gate_id] = matches[0]
    return located


_PINNED_REF_RE = re.compile(r"[0-9a-f]{40}")


def _pins_same_action(actual: Any, expected_ref: str) -> bool:
    """
    Return True when *actual* pins the same action as *expected_ref* to a SHA.

    Pre-edit projection tolerates a stale commit SHA — the catalog refresh is
    projected by ``--write`` — but not a different action, a missing pin, or a
    mutable ref.
    """
    if not isinstance(actual, str) or "@" not in actual:
        return False
    actual_repo, _, actual_ref = actual.rpartition("@")
    expected_repo, _, _ = expected_ref.rpartition("@")
    return actual_repo == expected_repo and _PINNED_REF_RE.fullmatch(actual_ref) is not None


def _step_matches(actual: Any, expected: dict[str, Any], *, strict: bool) -> bool:
    """Compare one job step; outside strict mode a stale action ref is tolerated."""
    if not isinstance(actual, dict):
        return False
    if strict:
        return actual == expected
    return {key: value for key, value in actual.items() if key != "uses"} == {
        key: value for key, value in expected.items() if key != "uses"
    }


def _validate_workflow_projection(
    text: str, gates: list[dict[str, Any]], *, strict: bool = True
) -> dict[str, Any]:
    """
    Validate the workflow shape and all registry-bound static metadata.

    ``strict=True`` (post-generation) requires the registry's exact hosted job
    IDs, ``needs`` lists, and check commands.  ``strict=False`` (pre-edit)
    locates the hosted jobs by their static catalog display names so a registry
    ``ci_job`` (F-005) or Make-target edit can be projected by ``--write``;
    static display and step metadata is validated identically in both modes
    except that a stale action pin is tolerated pre-edit, exactly like a stale
    ``needs`` list or check command, so ``--write`` can project a catalog
    refresh into the marked region.
    """
    workflow = _parse_workflow(text, "ci.yml")
    jobs = workflow.get("jobs")
    if not isinstance(jobs, dict):
        raise GeneratorError("ci.yml: jobs must be a mapping")
    _validate_unowned_job_rationales()
    bindings = _registry_bindings(gates)
    if strict:
        hosted_locations = {gate_id: bindings[gate_id][0] for gate_id in HOSTED_GATE_ORDER}
    else:
        hosted_locations = _locate_hosted_jobs(jobs, "ci.yml", allow_missing=True)
    expected_job_ids = UNOWNED_JOB_IDS | set(hosted_locations.values())
    actual_job_ids = frozenset(jobs)
    if actual_job_ids != expected_job_ids:
        raise GeneratorError(
            "ci.yml: unsupported hosted job set: "
            f"expected {sorted(expected_job_ids)!r}, got {sorted(actual_job_ids)!r}"
        )

    for gate_id in HOSTED_GATE_ORDER:
        job_id = hosted_locations.get(gate_id)
        if job_id is None:
            if strict:
                raise GeneratorError(f"ci.yml: hosted job for {gate_id!r} is missing")
            continue
        job = jobs.get(job_id)
        if not isinstance(job, dict):
            raise GeneratorError(f"ci.yml: jobs.{job_id} must be a mapping")
        spec = HOSTED_JOB_CATALOG[gate_id]
        make_target = bindings[gate_id][1]
        if job.get("name") != spec.display_name or job.get("runs-on") != "ubuntu-24.04":
            raise GeneratorError(f"ci.yml: jobs.{job_id} static display metadata drifted")
        steps = _job_steps(job, job_id)
        if len(steps) != 5:
            raise GeneratorError(f"ci.yml: jobs.{job_id} must retain exactly five steps")
        expected_refs = (
            CHECKOUT_REF,
            SETUP_PYTHON_REF,
            INSTALL_POETRY_REF,
        )
        if strict:
            actual_uses = tuple(step.get("uses") for step in steps if "uses" in step)
            if actual_uses != expected_refs:
                raise GeneratorError(f"ci.yml: jobs.{job_id} action versions/ordering drifted")
        else:
            # Pre-edit, an action pin one release behind the catalog is projected
            # by --write rather than rejected; the action identity and its pinned
            # shape must still hold, and post-generation validation requires the
            # catalog's exact refs.
            for step, expected_ref in zip(steps, expected_refs):
                if not _pins_same_action(step.get("uses"), expected_ref):
                    raise GeneratorError(f"ci.yml: jobs.{job_id} action versions/ordering drifted")
        expected_checkout: dict[str, Any] = {
            "name": "Checkout code",
            "uses": CHECKOUT_REF,
        }
        if spec.full_history:
            expected_checkout["with"] = {"fetch-depth": "0"}
        if not _step_matches(steps[0], expected_checkout, strict=strict):
            raise GeneratorError(f"ci.yml: jobs.{job_id} checkout step drifted")
        if not _step_matches(
            steps[1],
            {
                "name": "Set up Python 3.14",
                "uses": SETUP_PYTHON_REF,
                "with": {"python-version": "3.14"},
            },
            strict=strict,
        ):
            raise GeneratorError(f"ci.yml: jobs.{job_id} Python setup step drifted")
        if not _step_matches(
            steps[2],
            {
                "name": "Install Poetry",
                "uses": INSTALL_POETRY_REF,
                "with": {
                    "version": POETRY_VERSION,
                    "virtualenvs-create": "true",
                    "virtualenvs-in-project": "true",
                },
            },
            strict=strict,
        ):
            raise GeneratorError(f"ci.yml: jobs.{job_id} Poetry setup step drifted")
        if steps[3] != {"name": "Install dependencies", "run": "poetry install --with dev\n"}:
            raise GeneratorError(f"ci.yml: jobs.{job_id} dependency step drifted")
        if steps[4].get("name") != spec.check_step_name or "run" not in steps[4]:
            raise GeneratorError(f"ci.yml: jobs.{job_id} check step metadata drifted")
        if strict:
            # Owned field: post-generation it must equal the registry binding
            # exactly; pre-edit it may be stale so --write can project it.
            if steps[4].get("run") != f"make {make_target}\n":
                raise GeneratorError(f"ci.yml: jobs.{job_id} check command drifted")
        elif not isinstance(steps[4].get("run"), str):
            raise GeneratorError(f"ci.yml: jobs.{job_id} check command is not a string")

    expected_needs = _expected_needs(gates)
    for consumer, expected in expected_needs.items():
        job = jobs.get(consumer)
        if not isinstance(job, dict):
            raise GeneratorError(f"ci.yml: jobs.{consumer} must be a mapping")
        actual = job.get("needs", [])
        if isinstance(actual, str):
            actual_tuple = (actual,)
        elif isinstance(actual, list) and all(isinstance(value, str) for value in actual):
            actual_tuple = tuple(actual)
        else:
            raise GeneratorError(f"ci.yml: jobs.{consumer}.needs must be a string/list of strings")
        if len(set(actual_tuple)) != len(actual_tuple):
            raise GeneratorError(f"ci.yml: jobs.{consumer}.needs contains a duplicate predecessor")
        if strict:
            # Owned field: post-generation the needs must match the registry
            # bindings exactly, in order.
            if actual_tuple != expected:
                raise GeneratorError(
                    f"ci.yml: jobs.{consumer}.needs drifted: expected {list(expected)!r}, "
                    f"got {list(actual_tuple)!r}"
                )
        elif set(actual_tuple) - (set(FIXED_NEEDS) | set(hosted_locations.values())):
            # Pre-edit the generated predecessors may be stale (registry ci_job
            # rename) but must still name real workflow jobs or fixed needs.
            raise GeneratorError(
                f"ci.yml: jobs.{consumer}.needs contains an unsupported predecessor"
            )
    return workflow


def _render_job(gate_id: str, job_id: str, make_target: str) -> str:
    spec = HOSTED_JOB_CATALOG[gate_id]
    checkout = f"    - name: Checkout code\n      uses: {CHECKOUT_REF} {CHECKOUT_COMMENT}\n" + (
        "      with:\n        fetch-depth: 0\n" if spec.full_history else ""
    )
    return (
        f"  {job_id}:\n"
        f"    name: {spec.display_name}\n"
        "    runs-on: ubuntu-24.04\n"
        "\n"
        "    steps:\n"
        f"{checkout}"
        "\n"
        "    - name: Set up Python 3.14\n"
        f"      uses: {SETUP_PYTHON_REF} {SETUP_PYTHON_COMMENT}\n"
        "      with:\n"
        '        python-version: "3.14"\n'
        "\n"
        "    - name: Install Poetry\n"
        f"      uses: {INSTALL_POETRY_REF} {INSTALL_POETRY_COMMENT}\n"
        "      with:\n"
        f"        version: {POETRY_VERSION}\n"
        "        virtualenvs-create: true\n"
        "        virtualenvs-in-project: true\n"
        "\n"
        "    - name: Install dependencies\n"
        "      run: |\n"
        "        poetry install --with dev\n"
        "\n"
        f"    - name: {spec.check_step_name}\n"
        "      run: |\n"
        f"        make {make_target}\n"
    )


def _render_jobs(gates: list[dict[str, Any]]) -> str:
    bindings = _registry_bindings(gates)
    return "\n\n".join(
        _render_job(gate_id, *bindings[gate_id]).rstrip("\n") for gate_id in HOSTED_GATE_ORDER
    )


def _render_needs(gates: list[dict[str, Any]], consumer: str) -> str:
    expected = _expected_needs(gates)[consumer]
    return f"    needs: [{', '.join(expected)}]"


def _generated_make_targets(
    gates: list[dict[str, Any]],
) -> list[tuple[str, str, tuple[str, ...], str]]:
    """
    Return ``(gate_id, make_target, recipe, description)`` for generated gates.

    Every registry gate that declares a ``make_target`` must carry a
    ``make_recipe`` or be declared in ``HAND_OWNED_MAKE_TARGETS``; anything
    else fails closed so a new gate cannot silently ship without its Make
    target.  A hand-owned gate may not also declare a recipe.
    """
    generated: list[tuple[str, str, tuple[str, ...], str]] = []
    gate_ids = {gate["id"] for gate in gates}
    for gate in gates:
        gid = gate["id"]
        bindings = gate.get("bindings")
        target = bindings.get("make_target") if isinstance(bindings, dict) else None
        recipe = gate.get("make_recipe")
        hand_owned = gid in HAND_OWNED_MAKE_TARGETS
        if hand_owned and recipe is not None:
            raise GeneratorError(
                f"gate {gid!r}: declares both a make_recipe and a hand-owned exemption"
            )
        if hand_owned and not isinstance(target, str):
            raise GeneratorError(f"gate {gid!r}: hand-owned gate must declare a make_target")
        if not hand_owned and recipe is None and isinstance(target, str):
            raise GeneratorError(
                f"gate {gid!r}: make_target {target!r} has no make_recipe and is not "
                f"a declared hand-owned Makefile target"
            )
        if recipe is None:
            continue
        if not isinstance(target, str):
            raise GeneratorError(f"gate {gid!r}: make_recipe requires a string make_target")
        generated.append((gid, target, tuple(recipe), gate["description"]))
    stale = HAND_OWNED_MAKE_TARGETS - gate_ids
    if stale:
        raise GeneratorError(
            "hand-owned Make target exemption(s) name unknown gate(s): " + ", ".join(sorted(stale))
        )
    if not generated:
        raise GeneratorError("registry: no generated make_recipe target is declared")
    return generated


def _render_make_include(gates: list[dict[str, Any]]) -> str:
    """Render the generated ``scripts/gates.mk`` include from the registry."""
    generated = _generated_make_targets(gates)
    sections = [
        MAKE_INCLUDE_HEADER,
        ".PHONY: " + " ".join(target for _, target, _, _ in generated),
    ]
    for gate_id, target, recipe, description in generated:
        comment = MAKE_TARGET_COMMENTS.get(gate_id, description)
        comment_block = "\n".join(f"# {line}" for line in comment.splitlines())
        recipe_block = "\n".join(f"\t{line}" for line in recipe)
        sections.append(f"{comment_block}\n{target}:\n{recipe_block}")
    return "\n\n".join(sections) + "\n"


def _line_index(lines: list[str], marker: str) -> list[int]:
    return [index for index, line in enumerate(lines) if line.rstrip("\n") == marker]


def _replace_marked_region(
    lines: list[str], begin: str, end: str, replacement: list[str], label: str
) -> list[str]:
    begins = _line_index(lines, begin)
    ends = _line_index(lines, end)
    if len(begins) != 1 or len(ends) != 1:
        raise GeneratorError(f"{label}: expected exactly one marker pair")
    if begins[0] >= ends[0]:
        raise GeneratorError(f"{label}: marker order is invalid")
    return lines[: begins[0] + 1] + replacement + lines[ends[0] :]


def _all_markers_present(lines: list[str]) -> bool:
    markers = [JOB_BEGIN, JOB_END, *NEEDS_BEGIN.values(), *NEEDS_END.values()]
    return all(len(_line_index(lines, marker)) == 1 for marker in markers)


def _any_marker_present(lines: list[str]) -> bool:
    markers = [JOB_BEGIN, JOB_END, *NEEDS_BEGIN.values(), *NEEDS_END.values()]
    return any(_line_index(lines, marker) for marker in markers)


def _e2e_paths_line_indices(lines: list[str]) -> tuple[int, list[int]]:
    path_lines = [
        index for index, line in enumerate(lines) if re.match(r"^    paths:\s*$", line.rstrip("\n"))
    ]
    if len(path_lines) != 1:
        raise GeneratorError("e2e.yml: expected exactly one pull_request.paths declaration")
    paths_index = path_lines[0]
    pull_request_index = next(
        (
            index
            for index in range(paths_index - 1, -1, -1)
            if lines[index].rstrip("\n") == "  pull_request:"
        ),
        None,
    )
    if pull_request_index is None:
        raise GeneratorError("e2e.yml: pull_request.paths is misplaced")
    for index in range(pull_request_index + 1, paths_index):
        if lines[index].strip() and not lines[index].startswith("    "):
            raise GeneratorError("e2e.yml: pull_request.paths is misplaced")
    end = paths_index + 1
    while end < len(lines) and (
        not lines[end].strip()
        or lines[end].startswith("      - ")
        or lines[end].rstrip("\n") == E2E_PATHS_BEGIN
        or lines[end].rstrip("\n") == E2E_PATHS_END
    ):
        end += 1
    item_indices = [
        index for index in range(paths_index + 1, end) if lines[index].startswith("      - ")
    ]
    return paths_index, item_indices


def _render_e2e_paths(paths: tuple[str, ...]) -> list[str]:
    return [f"      - '{path}'\n" for path in paths]


def _validate_e2e_markers(lines: list[str]) -> tuple[int, int]:
    begins = _line_index(lines, E2E_PATHS_BEGIN)
    ends = _line_index(lines, E2E_PATHS_END)
    if len(begins) != 1 or len(ends) != 1:
        raise GeneratorError("e2e.yml: generated marker pair is incomplete or duplicated")
    begin, end = begins[0], ends[0]
    if begin >= end:
        raise GeneratorError("e2e.yml: generated marker order is invalid")
    paths_index, _ = _e2e_paths_line_indices(lines)
    pull_request_index = next(
        (
            index
            for index in range(paths_index - 1, -1, -1)
            if lines[index].rstrip() == "  pull_request:"
        ),
        None,
    )
    if pull_request_index is None or not pull_request_index < begin < end:
        raise GeneratorError("e2e.yml: generated markers are outside pull_request.paths")
    if begin != paths_index + 1:
        raise GeneratorError("e2e.yml: begin marker is not adjacent to paths sequence")
    if end != begin + 1 and any(
        not re.match(r"^      - .*$", line.rstrip("\n")) for line in lines[begin + 1 : end]
    ):
        raise GeneratorError("e2e.yml: generated region contains misplaced content")
    if any("GENERATED:" in line for line in lines[begin + 1 : end]):
        raise GeneratorError("e2e.yml: generated region contains nested markers")
    return begin, end


def expected_e2e_workflow_text(text: str, gates: list[dict[str, Any]]) -> str:
    """Return E2E workflow text with only the owned allowlist projected."""
    _parse_e2e_workflow(text)
    lines = text.splitlines(keepends=True)
    has_markers = any(_line_index(lines, marker) for marker in (E2E_PATHS_BEGIN, E2E_PATHS_END))
    if has_markers:
        _validate_e2e_markers(lines)
        replacement = _render_e2e_paths(_expected_e2e_paths(gates))
        lines = _replace_marked_region(
            lines, E2E_PATHS_BEGIN, E2E_PATHS_END, replacement, "E2E path region"
        )
    else:
        paths_index, path_items = _e2e_paths_line_indices(lines)
        replacement = [
            E2E_PATHS_BEGIN + "\n",
            *_render_e2e_paths(_expected_e2e_paths(gates)),
            E2E_PATHS_END + "\n",
        ]
        start = paths_index + 1
        end = path_items[-1] + 1 if path_items else start
        lines = lines[:start] + replacement + lines[end:]
    result = "".join(lines)
    _parse_e2e_workflow(result)
    _validate_e2e_markers(result.splitlines(keepends=True))
    return result


def _publish_gate_bindings(gates: list[dict[str, Any]]) -> dict[str, str]:
    """
    Validate and return the publish-context gate Make targets.

    The registry's ``publish`` context membership must equal the helper-owned
    catalog exactly: a publish-bound gate without a catalog step, or a catalog
    step for a gate outside the publish context, fails closed so the generated
    workflow cannot silently drift from the registry.
    """
    publish_gates = [gate for gate in gates if "publish" in gate["required_contexts"]]
    publish_ids = tuple(gate["id"] for gate in publish_gates)
    expected = frozenset(PUBLISH_GATE_ORDER)
    if frozenset(publish_ids) != expected or len(publish_ids) != len(PUBLISH_GATE_ORDER):
        raise GeneratorError(
            "unsupported publish gate set: "
            f"expected {list(PUBLISH_GATE_ORDER)!r}, got {list(publish_ids)!r}"
        )
    if set(PUBLISH_STEP_CATALOG) != expected:
        raise GeneratorError("publish step catalog does not match the supported gate set")
    bindings: dict[str, str] = {}
    for gate in publish_gates:
        make_target = gate["bindings"].get("make_target")
        if not isinstance(make_target, str):
            raise GeneratorError(f"publish gate {gate['id']!r} has no Make target")
        bindings[gate["id"]] = make_target
    return bindings


def _publish_run_lines(gate_id: str, bindings: dict[str, str]) -> tuple[str, ...]:
    """Return the shell lines of one publish gate step."""
    spec = PUBLISH_STEP_CATALOG[gate_id]
    command = f"make {bindings[gate_id]}"
    if spec.command_prefix is not None:
        command = f"{spec.command_prefix} {command}"
    return (command,)


def _publish_expected_run(gate_id: str, bindings: dict[str, str]) -> str:
    """Return the exact YAML-parsed ``run`` value of one publish gate step."""
    return "".join(f"{line}\n" for line in _publish_run_lines(gate_id, bindings))


def _render_publish_steps(gates: list[dict[str, Any]]) -> list[str]:
    """Render the owned publish gate-step lines in catalog order."""
    bindings = _publish_gate_bindings(gates)
    rendered: list[str] = []
    for index, gate_id in enumerate(PUBLISH_GATE_ORDER):
        spec = PUBLISH_STEP_CATALOG[gate_id]
        if index:
            rendered.append("\n")
        rendered.append(f"      - name: {spec.step_name}\n")
        rendered.append("        run: |\n")
        for line in _publish_run_lines(gate_id, bindings):
            rendered.append(f"          {line}\n")
    return rendered


def _publish_test_steps_span(lines: list[str]) -> tuple[int, int]:
    """Return the ``steps:`` line index and job end of the top-level ``test`` job."""
    headers = _top_level_job_headers(lines)
    starts = [index for index, job_id in headers if job_id == "test"]
    if len(starts) != 1:
        raise GeneratorError("publish.yml: expected exactly one top-level test job")
    start = starts[0]
    end = next((index for index, _ in headers if index > start), len(lines))
    steps_lines = [
        index for index in range(start + 1, end) if lines[index].rstrip("\n") == "    steps:"
    ]
    if len(steps_lines) != 1:
        raise GeneratorError("publish.yml: test job must declare exactly one steps list")
    return steps_lines[0], end


def _publish_step_entries(
    lines: list[str], steps_line: int, span_end: int
) -> list[tuple[int, int]]:
    """Return the ``(start, end)`` line slices of every test-job step entry."""
    starts = [
        index for index in range(steps_line + 1, span_end) if lines[index].startswith("      - ")
    ]
    entries: list[tuple[int, int]] = []
    for index, start in enumerate(starts):
        end = starts[index + 1] if index + 1 < len(starts) else span_end
        entries.append((start, end))
    return entries


def _publish_entry_content_end(lines: list[str], start: int, end: int) -> int:
    """Return the slice end excluding trailing blank lines."""
    content_end = end
    while content_end > start and not lines[content_end - 1].strip():
        content_end -= 1
    return content_end


def _match_publish_entries(
    lines: list[str], entries: list[tuple[int, int]]
) -> dict[str, tuple[int, int]]:
    """Locate catalog-owned step entries by their exact catalog name line."""
    located: dict[str, tuple[int, int]] = {}
    for gate_id in PUBLISH_GATE_ORDER:
        name = PUBLISH_STEP_CATALOG[gate_id].step_name
        needle = f"      - name: {name}\n"
        matches = [entry for entry in entries if needle in "".join(lines[entry[0] : entry[1]])]
        if len(matches) > 1:
            raise GeneratorError(f"publish.yml: duplicate gate step named {name!r}")
        if matches:
            located[gate_id] = matches[0]
    return located


def _any_publish_marker_present(lines: list[str]) -> bool:
    return any(_line_index(lines, marker) for marker in (PUBLISH_BEGIN, PUBLISH_END))


def _validate_publish_markers(lines: list[str]) -> None:
    """
    Prove the publish marker pair owns exactly the catalog-owned gate steps.

    Line matching alone is insufficient: a marker pair moved into another job,
    or stretched over a sibling step, must not authorize rewriting those bytes.
    """
    begins = _line_index(lines, PUBLISH_BEGIN)
    ends = _line_index(lines, PUBLISH_END)
    if len(begins) != 1 or len(ends) != 1:
        raise GeneratorError("publish.yml: generated marker pair is incomplete or duplicated")
    begin, end = begins[0], ends[0]
    if begin >= end:
        raise GeneratorError("publish.yml: generated marker order is invalid")
    steps_line, span_end = _publish_test_steps_span(lines)
    if not steps_line < begin < end < span_end:
        raise GeneratorError("publish.yml: generated markers are outside the test job's steps")
    if not lines[begin + 1].startswith("      - "):
        raise GeneratorError("publish.yml: begin marker is not adjacent to a gate step")
    entries = _publish_step_entries(lines, steps_line, span_end)
    located = _match_publish_entries(lines, entries)
    missing = [gate_id for gate_id in PUBLISH_GATE_ORDER if gate_id not in located]
    if missing:
        raise GeneratorError(
            "publish.yml: generated region is missing gate step(s): " + ", ".join(missing)
        )
    starts = [located[gate_id][0] for gate_id in PUBLISH_GATE_ORDER]
    if begin + 1 != starts[0]:
        raise GeneratorError("publish.yml: begin marker is not adjacent to the first gate step")
    last_start, last_end = located[PUBLISH_GATE_ORDER[-1]]
    if not last_start < end < last_end:
        raise GeneratorError("publish.yml: end marker is not at the gate-step region boundary")
    inside = [start for start, _ in entries if begin < start < end]
    if inside != starts:
        raise GeneratorError("publish.yml: marker region contains non-gate steps")
    if any("GENERATED:" in line for line in lines[begin + 1 : end]):
        raise GeneratorError("publish.yml: generated region contains nested markers")
    # A comment line does not end the last step's YAML mapping: step-level
    # content after the end marker still attaches to the final gate step, so
    # it must fail closed instead of riding along unchecked.
    trailing = lines[end + 1 : last_end]
    if any(
        line.strip() and not line.lstrip().startswith("#") and len(line) - len(line.lstrip(" ")) > 6
        for line in trailing
    ):
        raise GeneratorError(
            "publish.yml: content after the end marker belongs to the last gate step"
        )


def _bootstrap_publish_markers(lines: list[str], gates: list[dict[str, Any]]) -> list[str]:
    """Wrap the existing catalog-owned gate steps in the generated marker pair."""
    _publish_gate_bindings(gates)
    steps_line, span_end = _publish_test_steps_span(lines)
    entries = _publish_step_entries(lines, steps_line, span_end)
    located = _match_publish_entries(lines, entries)
    if not located:
        raise GeneratorError("publish.yml: no catalog-owned gate steps were found")
    order = [gate_id for gate_id in PUBLISH_GATE_ORDER if gate_id in located]
    entry_index = {entry: index for index, entry in enumerate(entries)}
    indices = [entry_index[located[gate_id]] for gate_id in order]
    if indices != list(range(indices[0], indices[0] + len(indices))):
        raise GeneratorError("publish.yml: catalog-owned gate steps are not one contiguous region")
    region_start = located[order[0]][0]
    region_end = _publish_entry_content_end(lines, *located[order[-1]])
    replacement = [PUBLISH_BEGIN + "\n", *_render_publish_steps(gates), PUBLISH_END + "\n"]
    return lines[:region_start] + replacement + lines[region_end:]


def _validate_publish_projection(text: str, gates: list[dict[str, Any]], *, strict: bool) -> None:
    """
    Validate the publish gate-step projection.

    ``strict=True`` (post-generation) requires every catalog step, its exact
    order, and its exact registry-derived run value.  ``strict=False``
    (pre-edit) locates the steps by their catalog names so a stale owned run
    value can be projected by ``--write``, exactly like the hosted region.
    """
    workflow = _parse_workflow(text, "publish.yml")
    jobs = workflow.get("jobs")
    if not isinstance(jobs, dict):
        raise GeneratorError("publish.yml: jobs must be a mapping")
    job = jobs.get("test")
    if not isinstance(job, dict):
        raise GeneratorError("publish.yml: jobs.test must be a mapping")
    steps = _job_steps(job, "test")
    bindings = _publish_gate_bindings(gates)
    catalog_names = {PUBLISH_STEP_CATALOG[gate_id].step_name for gate_id in PUBLISH_GATE_ORDER}
    occurrences: dict[str, list[tuple[str, int]]] = {name: [] for name in catalog_names}
    for job_id, job_value in jobs.items():
        if not isinstance(job_value, dict):
            continue
        job_steps = job_value.get("steps", [])
        if not isinstance(job_steps, list):
            continue
        for index, step in enumerate(job_steps):
            if isinstance(step, dict) and step.get("name") in catalog_names:
                occurrences[step["name"]].append((job_id, index))
    located: list[tuple[int, str]] = []
    for gate_id in PUBLISH_GATE_ORDER:
        spec = PUBLISH_STEP_CATALOG[gate_id]
        matches = occurrences[spec.step_name]
        if len(matches) > 1:
            raise GeneratorError(f"publish.yml: duplicate gate step named {spec.step_name!r}")
        if not matches:
            if strict:
                raise GeneratorError(f"publish.yml: gate step named {spec.step_name!r} is missing")
            continue
        job_id, index = matches[0]
        if job_id != "test":
            raise GeneratorError(
                f"publish.yml: gate step {spec.step_name!r} is outside the test job"
            )
        run = steps[index].get("run")
        if not isinstance(run, str):
            raise GeneratorError(f"publish.yml: gate step {spec.step_name!r} has no run block")
        if strict and run != _publish_expected_run(gate_id, bindings):
            raise GeneratorError(f"publish.yml: gate step {spec.step_name!r} run drifted")
        located.append((index, gate_id))
    indices = [index for index, _ in located]
    if indices != sorted(indices):
        raise GeneratorError("publish.yml: catalog-owned gate steps are out of order")


def expected_publish_workflow_text(text: str, gates: list[dict[str, Any]]) -> str:
    """Return publish workflow text with only the owned gate-step region projected."""
    _validate_publish_projection(text, gates, strict=False)
    lines = text.splitlines(keepends=True)
    if _any_publish_marker_present(lines):
        _validate_publish_markers(lines)
        lines = _replace_marked_region(
            lines,
            PUBLISH_BEGIN,
            PUBLISH_END,
            _render_publish_steps(gates),
            "publish gate-step region",
        )
    else:
        lines = _bootstrap_publish_markers(lines, gates)
    result = "".join(lines)
    _validate_publish_projection(result, gates, strict=True)
    _validate_publish_markers(result.splitlines(keepends=True))
    return result


def _top_level_job_headers(lines: list[str]) -> list[tuple[int, str]]:
    """Find job headers beneath ``jobs:`` without interpreting YAML scalars."""
    jobs_line = next((i for i, line in enumerate(lines) if line.rstrip() == "jobs:"), None)
    if jobs_line is None:
        raise GeneratorError("ci.yml: jobs section is missing")
    headers: list[tuple[int, str]] = []
    header_re = re.compile(r"^  ([A-Za-z][A-Za-z0-9_-]*):\s*$")
    for index in range(jobs_line + 1, len(lines)):
        match = header_re.match(lines[index].rstrip("\n"))
        if match:
            headers.append((index, match.group(1)))
    return headers


def _locate_hosted_job_headers(lines: list[str], *, allow_missing: bool = False) -> list[int]:
    """
    Locate the sixteen hosted job header lines by their display names.

    Use static display metadata to find the (possibly stale) hosted job IDs;
    this permits a registry ``ci_job`` (F-005) or Make-target edit while
    keeping the bootstrap independent of generated job text.
    """
    headers = _top_level_job_headers(lines)
    starts: list[int] = []
    for gate_id in HOSTED_GATE_ORDER:
        expected_name = HOSTED_JOB_CATALOG[gate_id].display_name
        found = [
            index
            for index, _job_id in headers
            if f"    name: {expected_name}\n"
            in "".join(
                lines[
                    index : next(
                        (position for position, _ in headers if position > index), len(lines)
                    )
                ]
            )
        ]
        if not found and allow_missing:
            continue
        if len(found) != 1:
            raise GeneratorError(f"hosted job bootstrap: expected one job named {expected_name!r}")
        starts.append(found[0])
    if not starts:
        return []
    headers_between = [position for position, _ in headers if starts[0] <= position <= starts[-1]]
    if starts != sorted(starts) or headers_between != starts:
        raise GeneratorError(
            "hosted job bootstrap: registry-bound jobs are not one contiguous region"
        )
    return starts


def _bootstrap_job_markers(lines: list[str], gates: list[dict[str, Any]]) -> list[str]:
    starts = _locate_hosted_job_headers(lines, allow_missing=True)
    if not starts:
        raise GeneratorError("hosted job bootstrap: no catalog-owned jobs were found")
    first = starts[0]
    last = starts[-1]
    next_header = next(
        (position for position, _ in _top_level_job_headers(lines) if position > last), len(lines)
    )
    end = next_header
    while end > last and not lines[end - 1].strip():
        end -= 1
    generated = _render_jobs(gates).splitlines(keepends=True)
    generated = [line if line.endswith("\n") else line + "\n" for line in generated]
    return lines[:first] + [JOB_BEGIN + "\n", *generated, JOB_END + "\n"] + lines[end:]


def _sync_needs_markers(lines: list[str], gates: list[dict[str, Any]]) -> list[str]:
    headers = _top_level_job_headers(lines)
    locations = {job_id: index for index, job_id in headers}
    for consumer in NEEDS_BEGIN:
        if consumer not in locations:
            raise GeneratorError(f"needs bootstrap: job {consumer!r} is missing")
        start = locations[consumer]
        end = next((position for position, _ in headers if position > start), len(lines))
        needs_lines = [
            index
            for index in range(start + 1, end)
            if re.match(r"^    needs:\s*", lines[index].rstrip("\n"))
        ]
        if len(needs_lines) != 1:
            raise GeneratorError(f"needs bootstrap: expected one needs line for {consumer}")
        line_index = needs_lines[0]
        replacement = [
            NEEDS_BEGIN[consumer] + "\n",
            _render_needs(gates, consumer) + "\n",
            NEEDS_END[consumer] + "\n",
        ]
        lines = lines[:line_index] + replacement + lines[line_index + 1 :]
        headers = _top_level_job_headers(lines)
        locations = {job_id: index for index, job_id in headers}
    return lines


def _validate_marked_regions(lines: list[str], gates: list[dict[str, Any]]) -> None:
    if not _all_markers_present(lines):
        raise GeneratorError("ci.yml: generated marker pairs are incomplete or duplicated")
    # Marker regions must be structurally owned by the exact top-level jobs they
    # name.  Line matching alone is insufficient: a marker moved into another
    # job (or into a scalar that happens to contain marker-looking text) must not
    # authorize rewriting that job's bytes.
    jobs_lines = _line_index(lines, "jobs:")
    if len(jobs_lines) != 1:
        raise GeneratorError("ci.yml: expected exactly one top-level jobs section")
    headers = _top_level_job_headers(lines)
    header_locations = {job_id: index for index, job_id in headers}
    job_begin = _line_index(lines, JOB_BEGIN)[0]
    job_end = _line_index(lines, JOB_END)[0]
    if not jobs_lines[0] < job_begin < job_end:
        raise GeneratorError("ci.yml: hosted job markers are not owned by the jobs section")
    # The region's job IDs may be stale (registry ci_job rename, F-005);
    # display-name ownership keeps the marked-region checks independent of
    # generated job text while still requiring exactly the hosted jobs.
    located_starts = _locate_hosted_job_headers(lines, allow_missing=True)
    located_by_index = {index: job_id for index, job_id in headers}
    located_ids = tuple(located_by_index[position] for position in located_starts)
    enclosed_jobs = tuple(job_id for index, job_id in headers if job_begin < index < job_end)
    if enclosed_jobs != located_ids:
        raise GeneratorError(
            "ci.yml: hosted job marker region must contain exactly the named top-level jobs "
            f"in order; got {list(enclosed_jobs)!r}"
        )
    if job_begin + 1 != header_locations[located_ids[0]]:
        raise GeneratorError("ci.yml: hosted job begin marker is not adjacent to its first job")
    last_job_start = header_locations[located_ids[-1]]
    if job_end <= last_job_start:
        raise GeneratorError("ci.yml: hosted job end marker is inside the last generated job")
    next_job_header = next((index for index, _ in headers if index > last_job_start), len(lines))
    if any(line.strip() for line in lines[job_end + 1 : next_job_header]):
        raise GeneratorError("ci.yml: hosted job end marker is not at the job-region boundary")

    if any("GENERATED:" in line for line in lines[job_begin + 1 : job_end]):
        raise GeneratorError("ci.yml: hosted job region contains nested generated markers")
    for consumer, begin in NEEDS_BEGIN.items():
        start = _line_index(lines, begin)[0]
        end = _line_index(lines, NEEDS_END[consumer])[0]
        if consumer not in header_locations:
            raise GeneratorError(f"ci.yml: needs marker consumer job {consumer!r} is missing")
        consumer_start = header_locations[consumer]
        consumer_end = next((index for index, _ in headers if index > consumer_start), len(lines))
        if not consumer_start < start < end < consumer_end:
            raise GeneratorError(
                f"ci.yml: needs marker region for {consumer} is not owned by its top-level job"
            )
        body = [line for line in lines[start + 1 : end] if line.strip()]
        if len(body) != 1 or not body[0].lstrip().startswith("needs:"):
            raise GeneratorError(f"ci.yml: needs marker region for {consumer} is malformed")


def expected_workflow_text(text: str, gates: list[dict[str, Any]]) -> str:
    """Return the deterministic generated workflow text for a registry."""
    _validate_workflow_projection(text, gates, strict=False)
    lines = text.splitlines(keepends=True)
    if _any_marker_present(lines):
        _validate_marked_regions(lines, gates)
    else:
        lines = _bootstrap_job_markers(lines, gates)
        lines = _sync_needs_markers(lines, gates)
    lines = _replace_marked_region(
        lines,
        JOB_BEGIN,
        JOB_END,
        [line + "\n" for line in _render_jobs(gates).splitlines()],
        "hosted job region",
    )
    for consumer in NEEDS_BEGIN:
        lines = _replace_marked_region(
            lines,
            NEEDS_BEGIN[consumer],
            NEEDS_END[consumer],
            [_render_needs(gates, consumer) + "\n"],
            f"needs region for {consumer}",
        )
    result = "".join(lines)
    _validate_workflow_projection(result, gates, strict=True)
    return result


def _atomic_write(path: Path, content: str) -> None:
    try:
        mode = path.stat().st_mode & 0o777
    except FileNotFoundError:
        mode = 0o644
    descriptor, temporary_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        temporary.chmod(mode)
        os.replace(temporary, path)
    except BaseException:
        temporary.unlink(missing_ok=True)
        raise


def sync_workflow(
    path: Path = DEFAULT_WORKFLOW, registry_path: Path = DEFAULT_REGISTRY
) -> tuple[bool, str]:
    """Compute expected content and return ``(drift, expected_text)``."""
    try:
        current = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise GeneratorError(f"cannot read workflow {path}: {exc}") from None
    gates = _parse_registry(registry_path)
    expected = expected_workflow_text(current, gates)
    return current != expected, expected


