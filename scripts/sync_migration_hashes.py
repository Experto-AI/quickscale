#!/usr/bin/env python3
"""
SA204(b) — migration hash manifest generator.

Records the content identity of the shipped modules' applied migration
files: the SHA-256 hash of each numbered migration, keyed by module name and
migration filename.  The manifest is checked in at
``scripts/migration_hashes.json``.  It works in shallow clones and without
Git tags because it hashes file content; later freeze and restore/update
checks compare this identity instead of a version label.

The shipped modules are enumerated through the authoritative discovery
contract (``quickscale_core.contracts.module_discovery``), so the manifest
covers exactly the release inventory and fails hard on an unexpected one.

Two modes:

  * ``--check`` (default): recompute the manifest from the shipped modules
    and compare it with the checked-in file.  Exit 0 when current; exit 1
    when a well-formed manifest has drifted, printing one deterministic
    unified diff on stdout; exit 2 on malformed or unreadable input.

  * ``--write``: regenerate the checked-in manifest from the shipped modules,
    atomically.  Exit 0 on success.

Exit codes:
    0 — the checked-in manifest matches the modules (check) or was written
    1 — a well-formed checked-in manifest has drifted (check mode only)
    2 — malformed or unreadable input, a discovery failure, or a filesystem
        error
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import sys
from pathlib import Path
from typing import Any, Final

from quickscale_core.contracts.module_discovery import (
    ImproperlyConfigured,
    authoritative_module_names,
    discover_shipped_module_paths,
)
from quickscale_core.migration_hashes import (
    MigrationHashError,
    compute_module_migration_hashes,
)

REPO_ROOT: Final[Path] = Path(__file__).resolve().parent.parent
DEFAULT_MANIFEST: Final[Path] = REPO_ROOT / "scripts" / "migration_hashes.json"

_SCHEMA_VERSION: Final[int] = 1
_DESCRIPTION: Final[str] = (
    "SHA-256 content identity of the shipped modules' applied migration files, "
    "keyed by module name and migration filename. Generated by "
    "scripts/sync_migration_hashes.py; regenerate with --write."
)


def _print_error(message: str) -> None:
    """Print a stable one-line error on stderr, never a traceback."""
    print(f"ERROR: {' '.join(str(message).split())}", file=sys.stderr)


class ManifestError(ValueError):
    """A checked-in manifest that is not a well-formed schema-v1 document."""


def _reject_duplicate_keys(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    """Build a JSON object, failing closed on duplicate mapping keys."""
    mapping: dict[str, Any] = {}
    for key, value in pairs:
        if key in mapping:
            raise ManifestError(f"duplicate key {key!r}")
        mapping[key] = value
    return mapping


def _reject_constant(value: str) -> Any:
    """Reject the non-standard ``NaN``/``Infinity`` JSON constants."""
    raise ManifestError(f"non-finite JSON number: {value}")


def _is_strict_int(value: Any) -> bool:
    """Return whether ``value`` is an integer and not a boolean."""
    return isinstance(value, int) and not isinstance(value, bool)


def _load_checked_manifest(manifest_path: Path) -> None:
    """
    Validate the checked-in manifest as a schema-v1 document.

    Raises:
        ManifestError: If the file is not a strict JSON object with the
            expected schema version, module records, and digest strings.

    """
    text = manifest_path.read_text(encoding="utf-8")
    try:
        payload = json.loads(
            text,
            object_pairs_hook=_reject_duplicate_keys,
            parse_constant=_reject_constant,
        )
    except json.JSONDecodeError as exc:
        raise ManifestError(f"{manifest_path}: not valid JSON: {exc}") from exc
    schema_version = payload.get("schema_version") if isinstance(payload, dict) else None
    if not _is_strict_int(schema_version) or schema_version != _SCHEMA_VERSION:
        raise ManifestError(f"{manifest_path}: expected schema_version {_SCHEMA_VERSION}")
    modules = payload.get("modules")
    if not isinstance(modules, dict):
        raise ManifestError(f"{manifest_path}: expected a 'modules' object")
    for module_name, migrations in modules.items():
        if not isinstance(module_name, str) or not isinstance(migrations, dict):
            raise ManifestError(f"{manifest_path}: every module record must be an object")
        for filename, digest in migrations.items():
            if not isinstance(filename, str) or not isinstance(digest, str):
                raise ManifestError(
                    f"{manifest_path}: module '{module_name}' has a non-string entry"
                )


def _expected_manifest_text() -> str:
    """Render the manifest from the shipped modules' migration files."""
    names = authoritative_module_names()
    paths = discover_shipped_module_paths()
    if sorted(paths) != names:
        raise MigrationHashError(
            "Discovered module directories do not match the authoritative inventory: "
            f"{sorted(paths)} != {names}"
        )
    modules: dict[str, dict[str, str]] = {
        name: compute_module_migration_hashes(paths[name]) for name in names
    }
    payload: dict[str, Any] = {
        "schema_version": _SCHEMA_VERSION,
        "description": _DESCRIPTION,
        "modules": modules,
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def _write_manifest_text(manifest_path: Path, text: str) -> None:
    """Write the manifest text atomically next to the checked-in file."""
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    temporary = manifest_path.with_suffix(f"{manifest_path.suffix}.tmp")
    try:
        temporary.write_text(text, encoding="utf-8")
        os.replace(temporary, manifest_path)
    except BaseException:
        temporary.unlink(missing_ok=True)
        raise


def _check_manifest(manifest_path: Path) -> int:
    """Compare the checked-in manifest with the freshly rendered one."""
    expected_text = _expected_manifest_text()
    if not manifest_path.is_file():
        raise FileNotFoundError(manifest_path)
    _load_checked_manifest(manifest_path)
    current_text = manifest_path.read_text(encoding="utf-8")
    if current_text == expected_text:
        print(f"Migration hash manifest is current: {manifest_path}")
        return 0
    diff = difflib.unified_diff(
        current_text.splitlines(keepends=True),
        expected_text.splitlines(keepends=True),
        fromfile=str(manifest_path),
        tofile=f"{manifest_path} (generated)",
    )
    sys.stdout.write("".join(diff))
    return 1


def _write_manifest(manifest_path: Path) -> int:
    """Regenerate the checked-in manifest from the shipped modules."""
    expected_text = _expected_manifest_text()
    if manifest_path.is_file() and manifest_path.read_text(encoding="utf-8") == expected_text:
        print(f"Migration hash manifest already current: {manifest_path}")
        return 0
    _write_manifest_text(manifest_path, expected_text)
    print(f"Wrote migration hash manifest: {manifest_path}")
    return 0


def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Check or regenerate the migration hash manifest.",
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check",
        action="store_true",
        help="Verify the checked-in manifest is current (default)",
    )
    mode.add_argument(
        "--write",
        action="store_true",
        help="Regenerate the checked-in manifest",
    )
    parser.add_argument(
        "--manifest",
        default=None,
        type=str,
        help="Path to the checked-in manifest (default: scripts/migration_hashes.json)",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    """Parse arguments, then check or regenerate the manifest (exit 0/1/2)."""
    args = _parse_args(argv)
    manifest_path = Path(args.manifest).resolve() if args.manifest else DEFAULT_MANIFEST

    try:
        if args.write:
            return _write_manifest(manifest_path)
        return _check_manifest(manifest_path)
    except (MigrationHashError, ManifestError, ImproperlyConfigured) as exc:
        _print_error(str(exc))
        return 2
    except FileNotFoundError as exc:
        _print_error(f"File not found: {exc}")
        return 2
    except PermissionError as exc:
        _print_error(f"Permission denied: {exc}")
        return 2
    except OSError as exc:
        _print_error(f"I/O error: {exc}")
        return 2
    except Exception as exc:  # noqa: BLE001
        message = str(exc) if str(exc) else type(exc).__name__
        _print_error(f"Unexpected error: {message}")
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
